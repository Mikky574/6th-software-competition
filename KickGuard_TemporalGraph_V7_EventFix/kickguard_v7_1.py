"""
KickGuard Temporal-Graph V7.1
=============================

Design goals after V7 EventFix diagnostics:
- reuse validated event-aware reduced caches; never re-parse raw data unless missing
- learn event proximity as a continuous risk target instead of only 0/1
- augment the feature space with direction-invariant anomaly features
- use Temporal Graph only as a weak correction
- optionally blend with the previously proven TimeAware/old blend debug CSV
- never use OOF positive rate to decide final positive count
- emit fixed Top-K candidates: 112/116/120/124/128/132

Run from this directory, using the same work_v7 generated by EventFix:

python kickguard_v7_1.py \
  --train-dir ../train \
  --test-dir ../test \
  --work-dir ./work_v7 \
  --output-dir ./v7_1_submit

Optional old TimeAware blend:
  --timeaware-debug ./timeaware_blend_debug.csv

The external blend is optional. If the CSV is absent, V7.1 runs standalone.
"""
